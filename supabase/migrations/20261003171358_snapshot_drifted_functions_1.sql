-- check_uid_exists_globally(p_uid text)
CREATE OR REPLACE FUNCTION public.check_uid_exists_globally(p_uid text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_exists boolean;
    v_role text;
BEGIN
    IF auth.uid() IS NOT NULL THEN
        SELECT a.role INTO v_role
        FROM public.accounts a
        WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active'
        LIMIT 1;

        IF v_role IS NULL OR v_role NOT IN ('super_admin', 'server_admin', 'guild_admin', 'R4', 'R5', 'admin') THEN
            RAISE EXCEPTION 'forbidden';
        END IF;
    END IF;

    SELECT EXISTS(
        SELECT 1 FROM public.guild_members WHERE uid = TRIM(p_uid)
    ) INTO v_exists;
    RETURN v_exists;
END;
$function$;
REVOKE ALL ON FUNCTION public.check_uid_exists_globally(p_uid text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.check_uid_exists_globally(p_uid text) TO authenticated;
