-- gm_discord_create_guild(p_discord_user_id text, p_discord_username text, p_guild_tag text, p_server_number text)
CREATE OR REPLACE FUNCTION public.gm_discord_create_guild(p_discord_user_id text, p_discord_username text, p_guild_tag text, p_server_number text)
