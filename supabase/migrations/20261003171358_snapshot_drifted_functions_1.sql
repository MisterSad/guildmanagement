-- gm_admin_request_transfer(p_uid text, p_target_guild text)
CREATE OR REPLACE FUNCTION public.gm_admin_request_transfer(p_uid text, p_target_guild text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_role text;
    v_caller_guild text;
    v_caller_server text;
    v_target text;
    v_source_guild text;
    v_source_server text;
    v_target_server text;
    v_pseudo text;
    v_new_id uuid;
BEGIN
    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    IF v_role IS NULL OR v_role = 'member' THEN
        RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
    END IF;

    -- guild_admin requests into their own guild; super_admin and server_admin
    -- (who may not be bound to one guild) must pass an explicit target.
    IF v_role IN ('super_admin', 'server_admin') THEN
        IF p_target_guild IS NULL OR p_target_guild = '' THEN
            RETURN jsonb_build_object('ok', false, 'error', 'missing_target_guild');
        END IF;
        v_target := UPPER(p_target_guild);
    ELSE
        -- No fallback: an account without a guild has no guild to pull into.
        -- This used to default to 'ALPHA', a real tenant.
        IF v_caller_guild IS NULL OR v_caller_guild = '' THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
        v_target := v_caller_guild;
    END IF;

    IF v_role <> 'super_admin' AND NOT public.is_subscription_active(v_target) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'subscription_expired');
    END IF;

    -- Find the player's current guild.
    SELECT guild, pseudo INTO v_source_guild, v_pseudo
    FROM public.guild_members
    WHERE uid = p_uid
    ORDER BY created_at DESC
    LIMIT 1;

    IF v_source_guild IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'member_not_found');
    END IF;

    IF v_source_guild = v_target THEN
        RETURN jsonb_build_object('ok', false, 'error', 'same_guild');
    END IF;

    IF EXISTS (SELECT 1 FROM public.guild_members WHERE guild = v_target AND uid = p_uid) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'uid_already_in_target');
    END IF;

    SELECT server_number INTO v_source_server FROM public.guilds WHERE id = v_source_guild;
    SELECT server_number INTO v_target_server FROM public.guilds WHERE id = v_target;

    IF v_target_server IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'target_guild_not_found');
    END IF;

    IF v_role = 'server_admin' AND (
        v_caller_server IS NULL
        OR v_source_server <> v_caller_server
        OR (v_target_server <> v_caller_server AND NOT public.servers_in_open_migration_group(v_caller_server, v_target_server))
    ) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'permission_denied');
    END IF;

    IF v_source_server IS NULL OR v_target_server IS NULL
       OR (v_source_server <> v_target_server AND NOT public.servers_in_open_migration_group(v_source_server, v_target_server)) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'different_server');
    END IF;

    -- One pending request per player at a time.
    IF EXISTS (
        SELECT 1 FROM public.guild_transfers
        WHERE uid = p_uid AND status = 'pending'
    ) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'already_pending');
    END IF;

    -- An admin pull: the guild the player is LEAVING approves it.
    INSERT INTO public.guild_transfers (uid, pseudo, source_guild, target_guild, status, requested_by)
    VALUES (p_uid, v_pseudo, v_source_guild, v_target, 'pending', 'admin')
    RETURNING id INTO v_new_id;

    RETURN jsonb_build_object(
        'ok', true,
        'transfer_id', v_new_id,
        'source_guild', v_source_guild,
        'target_guild', v_target
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_admin_request_transfer(p_uid text, p_target_guild text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_admin_request_transfer(p_uid text, p_target_guild text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_admin_request_transfer(p_uid text, p_target_guild text) TO service_role;

-- gm_apply_data_retention()
CREATE OR REPLACE FUNCTION public.gm_apply_data_retention()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    c_audit_log_months      constant integer := 12;
    c_name_history_months   constant integer := 12;
    c_closed_request_days   constant integer := 90;
    v_audit        integer;
    v_names        integer;
    v_cache        integer;
    v_handles      integer;
BEGIN
    DELETE FROM public.system_audit_logs
     WHERE created_at < now() - make_interval(months => c_audit_log_months);
    GET DIAGNOSTICS v_audit = ROW_COUNT;

    DELETE FROM public.player_name_history
     WHERE changed_at < now() - make_interval(months => c_name_history_months);
    GET DIAGNOSTICS v_names = ROW_COUNT;

    DELETE FROM public.ocr_cache WHERE expires_at <= now();
    GET DIAGNOSTICS v_cache = ROW_COUNT;

    UPDATE public.guild_creation_requests
       SET discord_handle = NULL
     WHERE discord_handle IS NOT NULL
       AND status <> 'pending'
       AND COALESCE(reviewed_at, created_at) < now() - make_interval(days => c_closed_request_days);
    GET DIAGNOSTICS v_handles = ROW_COUNT;

    RETURN jsonb_build_object(
        'ok', true,
        'audit_logs_deleted', v_audit,
        'name_history_deleted', v_names,
        'ocr_cache_deleted', v_cache,
        'discord_handles_cleared', v_handles,
        'ran_at', now()
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_apply_data_retention() FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_apply_data_retention() TO service_role;

-- gm_approve_participant_submission(p_guild text, p_event_name text, p_session_id text, p_pseudo text)
CREATE OR REPLACE FUNCTION public.gm_approve_participant_submission(p_guild text, p_event_name text, p_session_id text, p_pseudo text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller_role text;
    v_caller_guild text;
    v_caller_server text;
    v_target_server text;
    v_target text;
    v_updated integer;
BEGIN
    IF p_guild IS NULL OR p_event_name IS NULL OR p_pseudo IS NULL OR p_session_id IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'missing_parameters');
    END IF;

    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_caller_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    IF v_caller_role IS NULL OR v_caller_role = 'member' THEN
        RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
    END IF;

    v_target := COALESCE(UPPER(p_guild), 'ALPHA');

    IF v_caller_role = 'guild_admin' THEN
        IF v_target <> COALESCE(v_caller_guild, '') THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
    ELSIF v_caller_role = 'server_admin' THEN
        SELECT server_number INTO v_target_server FROM public.guilds WHERE id = v_target;
        IF v_caller_server IS NULL OR v_target_server IS NULL OR v_target_server <> v_caller_server THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
    END IF;

    UPDATE public.event_participants
    SET is_pending = false
    WHERE guild = v_target
      AND event_name = p_event_name
      AND session_id = p_session_id
      AND LOWER(pseudo) = LOWER(p_pseudo);
    GET DIAGNOSTICS v_updated = ROW_COUNT;

    RETURN jsonb_build_object('ok', true, 'updated', v_updated);
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_approve_participant_submission(p_guild text, p_event_name text, p_session_id text, p_pseudo text) FROM PUBLIC, anon, authenticated, service_role;
