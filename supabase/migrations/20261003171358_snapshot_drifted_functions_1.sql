-- gm_claim_account_with_discord(p_id text, p_password text, p_discord_user_id text)
CREATE OR REPLACE FUNCTION public.gm_claim_account_with_discord(p_id text, p_password text, p_discord_user_id text)
 RETURNS TABLE(ok boolean, account_id text, role text, err text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_check    record;
    v_acc      record;
    v_existing text;
BEGIN
    -- The SAME password check the login path uses. D1 extracted it from
    -- gm_check_login precisely so the transition could not develop a second,
    -- divergent credential check.
    SELECT * INTO v_check FROM public.gm_verify_password(p_id, p_password);

    IF v_check.is_locked OR v_check.error IS NOT DISTINCT FROM 'account_locked' THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'account_locked'::text;
        RETURN;
    END IF;
    IF v_check.canonical_id IS NULL OR v_check.role IS NULL THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'invalid_credentials'::text;
        RETURN;
    END IF;
    IF v_check.status IS DISTINCT FROM 'active' THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'pending_approval'::text;
        RETURN;
    END IF;

    SELECT a.id, a.role INTO v_acc
    FROM public.accounts a WHERE a.id = v_check.canonical_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'invalid_credentials'::text;
        RETURN;
    END IF;

    IF EXISTS (SELECT 1 FROM public.discord_account_links l WHERE l.account_id = v_acc.id) THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'already_linked'::text;
        RETURN;
    END IF;

    SELECT l.account_id INTO v_existing
    FROM public.discord_account_links l WHERE l.discord_user_id = p_discord_user_id;
    IF v_existing IS NOT NULL THEN
        RETURN QUERY SELECT false, NULL::text, NULL::text, 'discord_already_linked'::text;
        RETURN;
    END IF;

    INSERT INTO public.discord_account_links (discord_user_id, account_id)
    VALUES (p_discord_user_id, v_acc.id);

    -- The irreversible part. One sign-in method at any instant, never two.
    -- This also retires the reversible `password_enc` copy that finding C0 was
    -- about, for this account, permanently.
    UPDATE public.accounts
    SET password_hash   = NULL,
        password_enc    = NULL,
        session_version = COALESCE(session_version, 0) + 1
    WHERE id = v_acc.id;

    -- Backup codes go too. The Edge Function issues a FRESH set immediately
    -- for a super_admin, who has no administrator above them to unlink and
    -- reissue. (Passkeys no longer exist: removed 2026-10-03.)
    DELETE FROM public.account_backup_codes b WHERE b.account_id = v_acc.id;

    RETURN QUERY SELECT true, v_acc.id, v_acc.role, NULL::text;
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_claim_account_with_discord(p_id text, p_password text, p_discord_user_id text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_claim_account_with_discord(p_id text, p_password text, p_discord_user_id text) TO service_role;

