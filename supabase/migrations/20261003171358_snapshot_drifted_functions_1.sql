-- gm_generate_account_id(p_base text)
CREATE OR REPLACE FUNCTION public.gm_generate_account_id(p_base text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_base      text;
    v_candidate text;
    v_suffix    text;
    v_alphabet  CONSTANT text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
    i           int;
    j           int;
BEGIN
    -- Fold accented Latin to ASCII FIRST. Stripping straight to [A-Za-z0-9_]
    -- turns an ordinary Discord name like 'Ärès_Actual' into 'rs_Actual',
    -- unrecognisable to its owner. translate() rather than the unaccent
    -- extension: deterministic, no extension to install, and no schema
    -- qualification needed under search_path = ''.
    v_base := translate(
        COALESCE(p_base, ''),
        'ÀÁÂÃÄÅàáâãäåÈÉÊËèéêëÌÍÎÏìíîïÒÓÔÕÖØòóôõöøÙÚÛÜùúûüÝýÿÑñÇçŠšŽžÐðÞþ',
        'AAAAAAaaaaaaEEEEeeeeIIIIiiiiOOOOOOooooooUUUUuuuuYyyNnCcSsZzDdTt'
    );
    v_base := replace(replace(replace(v_base, 'Æ', 'AE'), 'æ', 'ae'), 'ß', 'ss');
    v_base := replace(replace(v_base, 'Œ', 'OE'), 'œ', 'oe');
    v_base := regexp_replace(v_base, '[^A-Za-z0-9_]', '', 'g');
    v_base := left(v_base, 20);
    IF length(v_base) < 3 THEN
        v_base := 'Commander';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.accounts a WHERE lower(a.id) = lower(v_base)) THEN
        RETURN v_base;
    END IF;

    FOR i IN 1..12 LOOP
        v_suffix := '';
        FOR j IN 1..4 LOOP
            v_suffix := v_suffix || substr(v_alphabet, 1 + floor(random() * length(v_alphabet))::int, 1);
        END LOOP;
        v_candidate := left(v_base, 20) || '_' || v_suffix;
        IF NOT EXISTS (SELECT 1 FROM public.accounts a WHERE lower(a.id) = lower(v_candidate)) THEN
            RETURN v_candidate;
        END IF;
    END LOOP;

    RETURN 'd' || COALESCE(NULLIF(regexp_replace(COALESCE(p_base, ''), '\D', '', 'g'), ''), extract(epoch from clock_timestamp())::bigint::text);
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_generate_account_id(p_base text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_generate_account_id(p_base text) TO service_role;

-- gm_get_player_event_history(p_uid text, p_limit integer)
CREATE OR REPLACE FUNCTION public.gm_get_player_event_history(p_uid text, p_limit integer DEFAULT 60)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_member record;
    v_events jsonb;
BEGIN
    SELECT pseudo, guild INTO v_member
    FROM public.guild_members
    WHERE uid = TRIM(p_uid)
    LIMIT 1;

    IF v_member.pseudo IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'player_not_found');
    END IF;

    IF auth.uid() IS NOT NULL THEN
        IF NOT (
            public.is_super_admin() OR
            public.check_user_guild_access(v_member.guild) OR
            EXISTS (
                SELECT 1 FROM public.accounts a
                WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND (a.uid = p_uid OR a.id = p_uid) AND a.status = 'active'
            )
        ) THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
    END IF;

    WITH guild_rows AS (
        SELECT
            UPPER(COALESCE(ep.event_name, '')) AS ev_key,
            COALESCE(ep.session_id, ep.week_start::text) AS sess_key,
            (COALESCE(ep.score, 0) + COALESCE(ep.score_prep, 0) + COALESCE(ep.score_pvp, 0)) AS total_score,
            (ep.participated > 0 OR ep.sub_present = true) AS counted
        FROM public.event_participants ep
        WHERE ep.guild = v_member.guild
    ),
    session_stats AS (
        SELECT ev_key, sess_key,
               ROUND(AVG(total_score) FILTER (WHERE counted OR total_score > 0)) AS avg_score,
               MAX(total_score) AS max_score
        FROM guild_rows
        GROUP BY ev_key, sess_key
    ),
    member_rows AS (
        SELECT
            UPPER(COALESCE(ep.event_name, 'OTHER')) AS ev_key,
            ep.session_id,
            ep.week_start,
            COALESCE(ep.session_id, ep.week_start::text) AS sess_key,
            (ep.participated > 0) AS participated,
            (COALESCE(ep.score, 0) + COALESCE(ep.score_prep, 0) + COALESCE(ep.score_pvp, 0)) AS player_score,
            COALESCE(ep.late, false) AS late,
            COALESCE(ep.excused, false) AS excused,
            COALESCE(ep.sub_present, false) AS sub_present,
            COALESCE(ep.appointed, false) AS appointed
        FROM public.event_participants ep
        WHERE ep.guild = v_member.guild AND ep.pseudo = v_member.pseudo
        ORDER BY ep.week_start DESC
        LIMIT LEAST(p_limit, 200)
    )
    SELECT jsonb_object_agg(t.ev_key, t.ev_data) INTO v_events
    FROM (
        SELECT
            mr.ev_key,
            jsonb_build_object(
                'count', COUNT(*),
                'attended', COUNT(*) FILTER (WHERE mr.participated OR mr.sub_present),
                'rate', CASE WHEN COUNT(*) > 0
                             THEN ROUND((COUNT(*) FILTER (WHERE mr.participated OR mr.sub_present))::numeric / COUNT(*)::numeric * 100)
                             ELSE 0 END,
                'history', jsonb_agg(
                    jsonb_build_object(
                        'session_id', mr.session_id,
                        'week_start', mr.week_start,
                        'participated', mr.participated,
                        'score', mr.player_score,
                        'guild_avg_score', COALESCE(ss.avg_score, 0),
                        'guild_max_score', COALESCE(ss.max_score, 0),
                        'late', mr.late,
                        'excused', mr.excused,
                        'sub_present', mr.sub_present,
                        'appointed', mr.appointed
                    ) ORDER BY mr.week_start DESC
                )
            ) AS ev_data
        FROM member_rows mr
        LEFT JOIN session_stats ss ON ss.ev_key = mr.ev_key AND ss.sess_key = mr.sess_key
        GROUP BY mr.ev_key
    ) t;

    RETURN jsonb_build_object(
        'ok', true,
        'guild', v_member.guild,
        'pseudo', v_member.pseudo,
        'events', COALESCE(v_events, '{}'::jsonb)
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_get_player_event_history(p_uid text, p_limit integer) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_get_player_event_history(p_uid text, p_limit integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_get_player_event_history(p_uid text, p_limit integer) TO service_role;

