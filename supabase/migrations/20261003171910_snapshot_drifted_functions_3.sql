GRANT EXECUTE ON FUNCTION public.gm_save_chest_tiers(p_guild text, p_event_name text, p_tiers jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_save_chest_tiers(p_guild text, p_event_name text, p_tiers jsonb) TO service_role;

-- gm_snowflake_created_at(p_snowflake text)
CREATE OR REPLACE FUNCTION public.gm_snowflake_created_at(p_snowflake text)
 RETURNS timestamp with time zone
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
DECLARE
    v_epoch CONSTANT bigint := 1420070400000;  -- 2015-01-01T00:00:00Z
    v_ms    bigint;
BEGIN
    -- Anything implausible returns NULL, never an epoch-0 date that would
    -- sail through an age check.
    IF p_snowflake IS NULL OR p_snowflake !~ '^[0-9]{17,20}$' THEN RETURN NULL; END IF;
    v_ms := (p_snowflake::numeric / 4194304)::bigint + v_epoch;  -- >> 22
    IF v_ms < v_epoch THEN RETURN NULL; END IF;
    RETURN to_timestamp(v_ms / 1000.0);
END;
