-- gm_get_player_metrics_history(p_uid text, p_limit integer)
CREATE OR REPLACE FUNCTION public.gm_get_player_metrics_history(p_uid text, p_limit integer DEFAULT 12)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_member record;
    v_history jsonb;
BEGIN
    SELECT pseudo, guild INTO v_member
    FROM public.guild_members
    WHERE uid = TRIM(p_uid)
    LIMIT 1;

    IF v_member.pseudo IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'player_not_found');
    END IF;

    IF auth.uid() IS NOT NULL THEN
        IF NOT (
            public.is_super_admin() OR
            public.check_user_guild_access(v_member.guild) OR
            EXISTS (
                SELECT 1 FROM public.accounts a
                WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND (a.uid = p_uid OR a.id = p_uid) AND a.status = 'active'
            )
        ) THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
    END IF;

    SELECT jsonb_agg(h ORDER BY h.week_start DESC)
    INTO v_history
    FROM (
        SELECT week_start, total_power, tech_power, champion_power, crew_power, flagship_power, fleet_rating, glory_score, created_at
        FROM public.player_metrics_history
        WHERE guild = v_member.guild AND pseudo = v_member.pseudo
        ORDER BY week_start DESC
        LIMIT LEAST(p_limit, 52)
    ) h;

    RETURN jsonb_build_object(
        'ok', true,
        'guild', v_member.guild,
        'pseudo', v_member.pseudo,
        'history', COALESCE(v_history, '[]'::jsonb)
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_get_player_metrics_history(p_uid text, p_limit integer) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_get_player_metrics_history(p_uid text, p_limit integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_get_player_metrics_history(p_uid text, p_limit integer) TO service_role;

-- gm_guild_tag_history(p_guild text)
CREATE OR REPLACE FUNCTION public.gm_guild_tag_history(p_guild text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_guild      text := nullif(btrim(p_guild), '');
    v_last       timestamptz;
    v_rows       jsonb;
    v_is_super   boolean;
    v_role       text;
BEGIN
    IF v_guild IS NULL OR NOT public.check_user_guild_write_access(v_guild) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'unauthorized');
    END IF;

    v_is_super := public.is_super_admin();
    SELECT a.role INTO v_role
    FROM public.accounts a
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active'
    LIMIT 1;

    SELECT max(h.changed_at) INTO v_last
    FROM public.guild_tag_history h WHERE h.guild = v_guild;

    SELECT COALESCE(jsonb_agg(jsonb_build_object(
               'old_tag', x.old_tag, 'new_tag', x.new_tag, 'changed_at', x.changed_at
           ) ORDER BY x.changed_at DESC), '[]'::jsonb)
      INTO v_rows
    FROM (
        SELECT h.old_tag, h.new_tag, h.changed_at
        FROM public.guild_tag_history h
        WHERE h.guild = v_guild
        ORDER BY h.changed_at DESC
        LIMIT 20
    ) x;

    RETURN jsonb_build_object(
        'ok', true,
        'history', v_rows,
        'next_allowed_at', CASE WHEN v_last IS NULL THEN NULL ELSE v_last + interval '7 days' END,
        -- Same predicate as gm_rename_guild's authorisation.
        'can_rename', v_is_super OR v_role = 'guild_admin',
        -- The cooldown does not apply to a super_admin.
        'cooldown_applies', NOT v_is_super
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_guild_tag_history(p_guild text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_guild_tag_history(p_guild text) TO authenticated;
