-- gm_list_event_sessions(p_guild text)
CREATE OR REPLACE FUNCTION public.gm_list_event_sessions(p_guild text DEFAULT NULL::text)
 RETURNS TABLE(event_name text, display_name text, session_id text, week_start date, start_at timestamp with time zone, participants integer, participated_count integer, total_score bigint, granular boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller_role text;
    v_caller_guild text;
    v_caller_server text;
    v_target_guild text;
    v_target_server text;
BEGIN
    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_caller_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    -- Only admins (or super admins) may list sessions; members use the portal.
    IF v_caller_role IS NULL OR v_caller_role = 'member' THEN
        RETURN;
    END IF;

    IF v_caller_role = 'guild_admin' THEN
        v_target_guild := COALESCE(v_caller_guild, 'ALPHA');
    ELSIF v_caller_role = 'server_admin' THEN
        v_target_guild := COALESCE(p_guild, v_caller_guild, 'ALPHA');
        SELECT server_number INTO v_target_server FROM public.guilds WHERE id = v_target_guild;
        IF v_caller_server IS NULL OR v_target_server IS NULL OR v_target_server <> v_caller_server THEN
            RETURN;
        END IF;
    ELSE
        v_target_guild := COALESCE(p_guild, v_caller_guild, 'ALPHA');
    END IF;

    RETURN QUERY
    SELECT base.event_name,
           base.display_name,
           base.session_id,
           base.week_start,
           base.start_at,
           base.participants,
           base.participated_count,
           base.total_score,
           EXISTS (
               SELECT 1 FROM public.war_sessions ws
               WHERE ws.guild = v_target_guild
                 AND ws.event_name = base.event_name
                 AND ws.session_id = base.session_id
           ) AS granular
    FROM (
        SELECT
            ep.event_name,
            COALESCE(es.event_name, ep.event_name) AS display_name,
            COALESCE(ep.session_id, ep.week_start::text) AS session_id,
            MIN(ep.week_start) AS week_start,
            MAX(es.start_at) AS start_at,
            COUNT(*)::integer AS participants,
            SUM(CASE WHEN ep.participated > 0 OR COALESCE(ep.score, 0) > 0 OR COALESCE(ep.score_prep, 0) > 0 OR COALESCE(ep.score_pvp, 0) > 0 THEN 1 ELSE 0 END)::integer AS participated_count,
            SUM(COALESCE(ep.score, 0) + COALESCE(ep.score_prep, 0) + COALESCE(ep.score_pvp, 0))::bigint AS total_score
        FROM public.event_participants ep
        LEFT JOIN public.event_status es
          ON es.guild = ep.guild
         AND es.session_id = ep.session_id
         AND (
           LOWER(es.event_name) = LOWER(ep.event_name)
           OR (ep.event_name = 'Shadowfront' AND es.event_name LIKE 'Shadowfront%')
         )
        WHERE ep.guild = v_target_guild
        GROUP BY ep.event_name, COALESCE(es.event_name, ep.event_name), COALESCE(ep.session_id, ep.week_start::text)
    ) base
    ORDER BY COALESCE(
      base.start_at,
      CASE
        WHEN base.session_id ~ '-[0-9]{8}(-[0-9]+)?$'
        THEN to_timestamp(
               substring(base.session_id FROM '-([0-9]{8})'),
               'YYYYMMDD'
             ) AT TIME ZONE 'UTC'
        ELSE NULL
      END,
      (base.week_start || 'T12:00:00')::timestamptz
    ) DESC;
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_list_event_sessions(p_guild text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_list_event_sessions(p_guild text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_list_event_sessions(p_guild text) TO service_role;

-- gm_personal_kpis(p_uid text)
CREATE OR REPLACE FUNCTION public.gm_personal_kpis(p_uid text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_member record;
    v_total_attended int := 0;
    v_total_sessions int := 0;
    v_rate numeric := 0;
    v_current_week date := (date_trunc('week', CURRENT_DATE)::date);
    v_density_index numeric := 0;
    v_combativity_index numeric := 0;
    v_residual_power bigint := 0;
BEGIN
    SELECT m.uid, m.pseudo, m.guild, m.overall_power, m.role, m.created_at,
           COALESCE(m.tech_power, 0) as tech_power,
           COALESCE(m.champion_power, 0) as champion_power,
           COALESCE(m.crew_power, 0) as crew_power,
           COALESCE(m.flagship_power, 0) as flagship_power,
           COALESCE(m.fleet_rating, 0) as fleet_rating,
           COALESCE(m.glory_score, 0) as glory_score,
           m.metrics_updated_at
    INTO v_member
    FROM public.guild_members m
    WHERE m.uid = TRIM(p_uid)
    LIMIT 1;

    IF v_member.uid IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'player_not_found');
    END IF;

    IF auth.uid() IS NOT NULL THEN
        IF NOT (
            public.is_super_admin() OR
            public.check_user_guild_access(v_member.guild) OR
            EXISTS (
                SELECT 1 FROM public.accounts a
                WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND (a.uid = p_uid OR a.id = p_uid) AND a.status = 'active'
            )
        ) THEN
            RETURN jsonb_build_object('ok', false, 'error', 'forbidden');
        END IF;
    END IF;

    SELECT COUNT(DISTINCT public.gm_event_scoring_key(ep.event_name, ep.session_id, ep.week_start::text))
    INTO v_total_sessions
    FROM public.event_participants ep
    WHERE ep.guild = v_member.guild
      AND ep.week_start <= v_current_week
      AND LOWER(COALESCE(ep.event_name, '')) != 'glory'
      AND (ep.is_pending IS NOT TRUE);

    SELECT COUNT(DISTINCT public.gm_event_scoring_key(ep.event_name, ep.session_id, ep.week_start::text))
    INTO v_total_attended
    FROM public.event_participants ep
    WHERE ep.guild = v_member.guild
      AND ep.pseudo = v_member.pseudo
      AND ep.week_start <= v_current_week
      AND LOWER(COALESCE(ep.event_name, '')) != 'glory'
      AND (ep.is_pending IS NOT TRUE)
      AND (ep.participated > 0 OR ep.sub_present = true OR ep.score > 0 OR ep.score_prep > 0 OR ep.score_pvp > 0);

    IF v_total_sessions > 0 THEN
        v_rate := ROUND((v_total_attended::numeric / v_total_sessions::numeric) * 100, 1);
    END IF;

    IF v_member.overall_power > 0 THEN
        v_density_index := ROUND(
            ((v_member.tech_power + v_member.champion_power + v_member.crew_power + v_member.flagship_power)::numeric / v_member.overall_power::numeric) * 100,
            1
        );
        v_combativity_index := ROUND(
            (v_member.glory_score::numeric / v_member.overall_power::numeric),
            2
        );
    END IF;

    v_residual_power := GREATEST(
        0,
        v_member.overall_power - (v_member.tech_power + v_member.champion_power + v_member.crew_power)
    );

    RETURN jsonb_build_object(
        'ok', true,
        'pseudo', v_member.pseudo,
        'guild', v_member.guild,
        'overall_power', v_member.overall_power,
        'tech_power', v_member.tech_power,
        'champion_power', v_member.champion_power,
        'crew_power', v_member.crew_power,
        'flagship_power', v_member.flagship_power,
        'fleet_rating', v_member.fleet_rating,
        'glory_score', v_member.glory_score,
        'metrics_updated_at', v_member.metrics_updated_at,
        'density_index', v_density_index,
        'combativity_index', v_combativity_index,
        'residual_power', v_residual_power,
        'role', v_member.role,
        'attended', v_total_attended,
        'total_sessions', v_total_sessions,
        'participation_rate', v_rate
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_personal_kpis(p_uid text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_personal_kpis(p_uid text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_personal_kpis(p_uid text) TO service_role;

-- gm_player_stats(p_guild text, p_pseudo text, p_weeks integer)
CREATE OR REPLACE FUNCTION public.gm_player_stats(p_guild text, p_pseudo text, p_weeks integer DEFAULT 4)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_guild  text;
    v_pseudo text;
    v_n      integer;
    v_weeks  date[];
    v_result jsonb;
BEGIN
    v_guild  := nullif(btrim(p_guild), '');
    v_pseudo := nullif(btrim(p_pseudo), '');
    IF v_guild IS NULL OR v_pseudo IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'guild_and_pseudo_required');
    END IF;

    v_n := least(greatest(coalesce(p_weeks, 4), 1), 26);

    SELECT array_agg(w ORDER BY w DESC) INTO v_weeks
    FROM (
        SELECT DISTINCT ep.week_start AS w
        FROM public.event_participants ep
        WHERE ep.guild = v_guild
          AND ep.event_name <> 'Glory'
          AND ep.week_start <= (date_trunc('week', now() AT TIME ZONE 'UTC'))::date
        ORDER BY w DESC LIMIT v_n
    ) d;

    IF v_weeks IS NULL OR array_length(v_weeks, 1) IS NULL THEN
        v_weeks := ARRAY[(date_trunc('week', now() AT TIME ZONE 'UTC'))::date];
    END IF;

    WITH keyed AS MATERIALIZED (
        SELECT ep.pseudo, ep.week_start,
            CASE
              WHEN upper(ep.event_name) LIKE 'ARMS RACE%'      THEN 'Arms Race|'   || coalesce(ep.session_id, ep.week_start::text, '')
              WHEN upper(ep.event_name) = 'SHADOWFRONT'        THEN 'Shadowfront|' || coalesce(ep.week_start::text, '')
              WHEN upper(ep.event_name) = 'SVS'                THEN 'SvS|'         || coalesce(ep.week_start::text, '')
              WHEN upper(ep.event_name) = 'GVG'                THEN 'GvG|'         || coalesce(ep.week_start::text, '')
              WHEN upper(ep.event_name) = 'DEFEND TRADE ROUTE' THEN 'DTR|'         || coalesce(ep.session_id, ep.week_start::text, '')
              ELSE coalesce(ep.event_name, '') || '|' || coalesce(ep.session_id, ep.week_start::text, '')
            END AS skey,
            (coalesce(ep.participated, 0) > 0 OR ep.sub_present) AS present,
            coalesce(ep.excused, false) AS excused
        FROM public.event_participants ep
        WHERE ep.guild = v_guild
          AND ep.week_start = ANY (v_weeks)
          AND coalesce(ep.is_pending, false) = false
          AND ep.event_name <> 'Glory'
    ),
    per_key AS (
        SELECT pseudo, skey, split_part(skey, '|', 1) AS bucket, week_start,
               bool_or(present) AS present, bool_or(excused) AS excused
        FROM keyed GROUP BY pseudo, skey, week_start
    ),
    opportunities AS (SELECT DISTINCT skey, bucket, week_start FROM per_key),
    roster AS (
        SELECT gm.pseudo, date_trunc('week', gm.created_at)::date AS joined_week
        FROM public.guild_members gm WHERE gm.guild = v_guild
    ),
    -- Per member, their own eligible opportunities. Aggregated to the GUILD
    -- before it leaves this function: a player must not be able to read another
    -- member's attendance, so no per-member row is returned and no rank is
    -- computed. The comparison offered is against the guild, not against peers.
    member_opp AS (
        SELECT r.pseudo, o.bucket, count(*) AS opp
        FROM roster r
        JOIN opportunities o ON o.week_start >= r.joined_week
        WHERE NOT EXISTS (
            SELECT 1 FROM per_key pk WHERE pk.pseudo = r.pseudo AND pk.skey = o.skey AND pk.excused
        )
        GROUP BY r.pseudo, o.bucket
    ),
    guild_buckets AS (
        SELECT mo.bucket,
               sum(mo.opp) AS member_opportunities,
               (SELECT count(*) FROM per_key pk WHERE pk.bucket = mo.bucket AND pk.present) AS attendances,
               (SELECT count(DISTINCT skey) FROM opportunities o WHERE o.bucket = mo.bucket) AS sessions
        FROM member_opp mo GROUP BY mo.bucket
    ),
    player_buckets AS (
        SELECT mo.bucket,
               mo.opp,
               coalesce((SELECT count(*) FROM per_key pk
                          WHERE pk.pseudo = v_pseudo AND pk.bucket = mo.bucket AND pk.present), 0) AS att,
               coalesce((SELECT count(*) FROM per_key pk
                          WHERE pk.pseudo = v_pseudo AND pk.bucket = mo.bucket AND pk.excused), 0) AS exc
        FROM member_opp mo WHERE mo.pseudo = v_pseudo
    ),
    glory AS (
        SELECT max(coalesce(ep.score, 0))  AS best,
               count(*)                    AS weeks_recorded,
               max(ep.week_start)          AS last_week
        FROM public.event_participants ep
        WHERE ep.guild = v_guild AND ep.pseudo = v_pseudo
          AND ep.event_name = 'Glory' AND coalesce(ep.score, 0) > 0
    )
    SELECT jsonb_build_object(
        'ok', true,
        'guild', v_guild,
        'pseudo', v_pseudo,
        'weeks', coalesce(array_length(v_weeks, 1), 0),
        'player', jsonb_build_object(
            'buckets', coalesce((
                SELECT jsonb_object_agg(bucket, jsonb_build_object('att', att, 'opp', opp, 'exc', exc))
                FROM player_buckets), '{}'::jsonb)
        ),
        -- The guild side is a POOLED rate with the same eligibility rule:
        -- attendances over the sum of every member's own opportunities. Not
        -- "attendances / (sessions x roster)", which would pretend everyone was
        -- on the roster for every session.
        'guild_totals', jsonb_build_object(
            'roster_size', (SELECT count(*) FROM roster),
            'max_power', coalesce((SELECT max(coalesce(overall_power, 0)) FROM public.guild_members WHERE guild = v_guild), 0),
            'buckets', coalesce((
                SELECT jsonb_object_agg(bucket, jsonb_build_object(
                    'sessions', sessions, 'attendances', attendances, 'member_opportunities', member_opportunities))
                FROM guild_buckets), '{}'::jsonb)
        ),
        'glory', (SELECT jsonb_build_object(
            'best', coalesce(best, 0), 'weeks_recorded', coalesce(weeks_recorded, 0), 'last_week', last_week
        ) FROM glory)
    ) INTO v_result;

    RETURN v_result;
END
$function$;
REVOKE ALL ON FUNCTION public.gm_player_stats(p_guild text, p_pseudo text, p_weeks integer) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_player_stats(p_guild text, p_pseudo text, p_weeks integer) TO service_role;

-- gm_purge_guild_data(p_guild text)
CREATE OR REPLACE FUNCTION public.gm_purge_guild_data(p_guild text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_guild  text := nullif(btrim(p_guild), '');
    v_counts jsonb := '{}'::jsonb;
    v_n      int;
BEGIN
    IF v_guild IS NULL THEN
        RAISE EXCEPTION 'gm_purge_guild_data: missing guild';
    END IF;

    -- Every tag-carrying column WITHOUT a foreign key to guilds(id). Keep this
    -- list in step with gm_rename_guild (ADR-022);
    -- tests/guild_purge_migration.test.js checks it against the generated types.

    -- The roster first: its (guild, pseudo) cascade removes participations,
    -- scores, metrics, sanctions, squads and sign-ups.
    DELETE FROM public.guild_members WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('guild_members', v_n);

    PERFORM public.gm_revoke_auth_sessions(a.auth_user_id)
       FROM public.accounts a
      WHERE a.guild = v_guild AND a.auth_user_id IS NOT NULL
        AND (a.role IS NULL OR a.role IN ('guild_admin', 'member'));
    DELETE FROM public.accounts
     WHERE guild = v_guild AND (role IS NULL OR role IN ('guild_admin', 'member'));
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('accounts', v_n);
    UPDATE public.accounts a
       SET server_number = COALESCE(a.server_number, (SELECT g.server_number FROM public.guilds g WHERE g.id = v_guild)),
           guild = NULL
     WHERE a.guild = v_guild AND a.role IN ('server_admin', 'super_admin');
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('accounts_detached', v_n);

    DELETE FROM public.account_link_codes WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('account_link_codes', v_n);

    DELETE FROM public.banned_players WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('banned_players', v_n);

    DELETE FROM public.event_status WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('event_status', v_n);

    DELETE FROM public.guild_config WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('guild_config', v_n);

    DELETE FROM public.player_absences WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('player_absences', v_n);

    DELETE FROM public.system_audit_logs WHERE guild = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('system_audit_logs', v_n);

    -- Another guild's opponent catalogue keeps the opponent by name; only the
    -- link to a tenant that no longer exists is cleared.
    UPDATE public.war_opponents SET guild_ref = NULL WHERE guild_ref = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('war_opponents_guild_ref', v_n);

    -- The one FK to guilds(id) that is ON DELETE NO ACTION: a comment on a
    -- SERVER-wide wiki page, written by an officer of this guild. It would
    -- block the delete outright. The comment belongs to the server's wiki, so
    -- it stays; only its author's guild is cleared.
    UPDATE public.migration_wiki_comments SET author_guild_id = NULL WHERE author_guild_id = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('wiki_comments_detached', v_n);

    -- Everything else with a foreign key to guilds(id) goes by ON DELETE CASCADE.
    DELETE FROM public.guilds WHERE id = v_guild;
    GET DIAGNOSTICS v_n = ROW_COUNT; v_counts := v_counts || jsonb_build_object('guilds', v_n);

    RETURN v_counts;
END;
