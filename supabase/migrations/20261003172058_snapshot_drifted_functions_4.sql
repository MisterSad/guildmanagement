-- gm_submit_guild_request(p_guild_tag text, p_server_number text, p_admin_id text, p_discord_handle text, p_note text)
CREATE OR REPLACE FUNCTION public.gm_submit_guild_request(p_guild_tag text, p_server_number text, p_admin_id text, p_discord_handle text, p_note text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_tag text := upper(trim(p_guild_tag));
    v_admin_id text := trim(p_admin_id);
    v_discord text := trim(p_discord_handle);
    v_note text := NULLIF(trim(coalesce(p_note, '')), '');
    v_server text := trim(p_server_number);
    v_pending_count integer;
BEGIN
    IF v_tag IS NULL OR v_tag !~ '^[A-Z0-9_]{2,12}$' THEN
        RETURN jsonb_build_object('ok', false, 'error', 'invalid_guild_tag');
    END IF;
    IF v_server IS NULL OR v_server !~ '^[0-9]{4}$' THEN
        RETURN jsonb_build_object('ok', false, 'error', 'invalid_server_number');
    END IF;
    IF v_admin_id IS NULL OR length(v_admin_id) < 3 OR length(v_admin_id) > 32 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'invalid_admin_id');
    END IF;
    IF v_discord IS NULL OR length(v_discord) < 2 OR length(v_discord) > 40 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'invalid_discord_handle');
    END IF;
    IF v_note IS NOT NULL AND length(v_note) > 500 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'note_too_long');
    END IF;

    IF EXISTS (SELECT 1 FROM public.guilds g WHERE upper(g.id) = v_tag) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'tag_taken');
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.guild_creation_requests r
        WHERE upper(r.guild_tag) = v_tag AND r.status = 'pending'
    ) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'tag_taken');
    END IF;

    IF EXISTS (SELECT 1 FROM public.accounts a WHERE lower(a.id) = lower(v_admin_id)) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'admin_id_taken');
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.guild_creation_requests r
        WHERE lower(r.admin_id) = lower(v_admin_id) AND r.status = 'pending'
    ) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'admin_id_taken');
    END IF;

    SELECT count(*) INTO v_pending_count FROM public.guild_creation_requests WHERE status = 'pending';
    IF v_pending_count >= 200 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'too_many_pending_requests');
    END IF;

    INSERT INTO public.guild_creation_requests (guild_tag, server_number, admin_id, discord_handle, note)
    VALUES (v_tag, v_server, v_admin_id, v_discord, v_note);

    RETURN jsonb_build_object('ok', true);
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_submit_guild_request(p_guild_tag text, p_server_number text, p_admin_id text, p_discord_handle text, p_note text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_submit_guild_request(p_guild_tag text, p_server_number text, p_admin_id text, p_discord_handle text, p_note text) TO service_role;

-- gm_sync_shadowfront_participants(p_guild text, p_session_id text)
CREATE OR REPLACE FUNCTION public.gm_sync_shadowfront_participants(p_guild text, p_session_id text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller_role text;
    v_caller_guild text;
    v_caller_server text;
    v_target_server text;
    v_target text;
    v_inserted integer;
    v_week date;
BEGIN
    IF p_guild IS NULL OR p_session_id IS NULL OR p_session_id = '' THEN
        RAISE EXCEPTION 'missing_parameters';
    END IF;

    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_caller_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    IF v_caller_role IS NULL OR v_caller_role = 'member' THEN
        RAISE EXCEPTION 'not_authorized';
    END IF;

    v_target := COALESCE(UPPER(p_guild), 'ALPHA');

    IF v_caller_role = 'guild_admin' THEN
        IF v_target <> COALESCE(v_caller_guild, '') THEN
            RAISE EXCEPTION 'not_authorized';
        END IF;
    ELSIF v_caller_role = 'server_admin' THEN
        SELECT server_number INTO v_target_server FROM public.guilds WHERE id = v_target;
        IF v_caller_server IS NULL OR v_target_server IS NULL OR v_target_server <> v_caller_server THEN
            RAISE EXCEPTION 'not_authorized';
        END IF;
    END IF;

    -- Resolve week from event_status start_at date, falling back to current week start
    SELECT (date_trunc('week', es.start_at AT TIME ZONE 'UTC'))::date INTO v_week
    FROM public.event_status es
    WHERE es.guild = v_target AND es.session_id = p_session_id
    LIMIT 1;

    IF v_week IS NULL THEN
        SELECT (date_trunc('week', now() AT TIME ZONE 'UTC'))::date INTO v_week;
    END IF;

    WITH ins AS (
        INSERT INTO public.event_participants (guild, event_name, session_id, week_start, pseudo, participated)
        SELECT
            v_target,
            'Shadowfront',
            p_session_id,
            v_week,
            s.pseudo,
            0
        FROM public.shadowfront_squads s
        WHERE s.guild = v_target
          AND s.session_id = p_session_id
          AND EXISTS (
            SELECT 1 FROM public.guild_members gm
            WHERE gm.guild = v_target AND LOWER(gm.pseudo) = LOWER(s.pseudo)
          )
        ON CONFLICT (guild, event_name, session_id, pseudo) WHERE session_id IS NOT NULL DO NOTHING
        RETURNING 1
    )
    SELECT count(*) INTO v_inserted FROM ins;

    RETURN COALESCE(v_inserted, 0);
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_sync_shadowfront_participants(p_guild text, p_session_id text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_sync_shadowfront_participants(p_guild text, p_session_id text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_sync_shadowfront_participants(p_guild text, p_session_id text) TO service_role;

-- gm_transfer_guild_member(p_uid text, p_target_guild text, p_pseudo text)
CREATE OR REPLACE FUNCTION public.gm_transfer_guild_member(p_uid text, p_target_guild text, p_pseudo text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller_role text;
    v_caller_guild text;
    v_caller_server text;
    v_source_guild text;
    v_source_server text;
    v_target_server text;
    v_pseudo text;
    v_uid text;
BEGIN
    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_caller_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    IF v_caller_role IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'unauthorized');
    END IF;
    -- Moving a player is an officer act; a member must use request_guild_transfer.
    IF v_caller_role NOT IN ('super_admin', 'server_admin', 'guild_admin') THEN
        RETURN jsonb_build_object('ok', false, 'error', 'unauthorized');
    END IF;

    IF v_caller_role = 'super_admin' THEN
        IF p_pseudo IS NOT NULL AND p_pseudo <> '' THEN
            SELECT guild, pseudo, uid INTO v_source_guild, v_pseudo, v_uid
            FROM public.guild_members
            WHERE uid = p_uid AND LOWER(pseudo) = LOWER(p_pseudo)
            ORDER BY created_at DESC
            LIMIT 1;
        ELSE
            SELECT guild, pseudo, uid INTO v_source_guild, v_pseudo, v_uid
            FROM public.guild_members
            WHERE uid = p_uid
            ORDER BY created_at DESC
            LIMIT 1;
        END IF;
    ELSIF v_caller_role = 'server_admin' THEN
        SELECT guild, pseudo, uid INTO v_source_guild, v_pseudo, v_uid
        FROM public.guild_members
        WHERE uid = p_uid
        ORDER BY created_at DESC
        LIMIT 1;
    ELSE
        -- guild_admin: source guild must match own guild strictly (no fallback)
        IF v_caller_guild IS NULL THEN
            RETURN jsonb_build_object('ok', false, 'error', 'permission_denied');
        END IF;
        SELECT guild, pseudo, uid INTO v_source_guild, v_pseudo, v_uid
        FROM public.guild_members
        WHERE uid = p_uid
          AND guild = v_caller_guild;
    END IF;

    IF v_source_guild IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'member_not_found');
    END IF;

    -- Verify caller scope over source guild
    IF v_caller_role = 'guild_admin' AND v_caller_guild <> v_source_guild THEN
        RETURN jsonb_build_object('ok', false, 'error', 'permission_denied');
    END IF;

    SELECT server_number INTO v_source_server FROM public.guilds WHERE id = v_source_guild;
    SELECT server_number INTO v_target_server FROM public.guilds WHERE id = p_target_guild;

    IF v_caller_role = 'server_admin' AND (
        v_caller_server IS NULL
        OR v_source_server <> v_caller_server
        OR (v_target_server <> v_caller_server AND NOT public.servers_in_open_migration_group(v_caller_server, v_target_server))
    ) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'permission_denied');
    END IF;

    IF v_caller_role <> 'super_admin' AND NOT public.is_subscription_active(v_source_guild) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'subscription_expired');
    END IF;

    IF v_source_guild = p_target_guild THEN
        RETURN jsonb_build_object('ok', false, 'error', 'same_guild');
    END IF;

    IF v_target_server IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'target_guild_not_found');
    END IF;

    IF v_source_server IS NULL OR v_target_server IS NULL
       OR (v_source_server <> v_target_server AND NOT public.servers_in_open_migration_group(v_source_server, v_target_server)) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'different_server');
    END IF;

    IF EXISTS (SELECT 1 FROM public.guild_members WHERE guild = p_target_guild AND uid = v_uid) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'uid_already_in_target');
    END IF;

    IF EXISTS (SELECT 1 FROM public.guild_members WHERE guild = p_target_guild AND LOWER(pseudo) = LOWER(v_pseudo)) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'duplicate_pseudo_in_target');
    END IF;

    UPDATE public.guild_members
    SET guild = p_target_guild
    WHERE uid = v_uid
      AND pseudo = v_pseudo
      AND guild = v_source_guild;

    UPDATE public.accounts
    SET guild = p_target_guild
    WHERE uid = v_uid
      AND role = 'member';

    PERFORM public.gm_transfer_sync_related_rows(v_pseudo, v_source_guild, p_target_guild);

    RETURN jsonb_build_object(
        'ok', true,
        'pseudo', v_pseudo,
        'source_guild', v_source_guild,
        'target_guild', p_target_guild,
        'server_number', v_source_server
    );
END;
$function$;
REVOKE ALL ON FUNCTION public.gm_transfer_guild_member(p_uid text, p_target_guild text, p_pseudo text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.gm_transfer_guild_member(p_uid text, p_target_guild text, p_pseudo text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.gm_transfer_guild_member(p_uid text, p_target_guild text, p_pseudo text) TO service_role;

-- gm_unsync_shadowfront_participant(p_guild text, p_session_id text, p_pseudo text)
CREATE OR REPLACE FUNCTION public.gm_unsync_shadowfront_participant(p_guild text, p_session_id text, p_pseudo text)
 RETURNS TABLE(ok boolean, error text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
    v_caller_role text;
    v_caller_guild text;
    v_caller_server text;
    v_target_server text;
BEGIN
    IF p_guild IS NULL OR p_session_id IS NULL OR p_pseudo IS NULL THEN
        RETURN QUERY SELECT false, 'missing_parameters'::text;
        RETURN;
    END IF;

    SELECT a.role, a.guild, COALESCE(a.server_number, g.server_number)
    INTO v_caller_role, v_caller_guild, v_caller_server
    FROM public.accounts a
    LEFT JOIN public.guilds g ON g.id = a.guild
    WHERE a.auth_user_id = auth.uid() AND (SELECT public.gm_session_is_valid()) AND a.status = 'active';

    IF v_caller_role IS NULL OR v_caller_role = 'member' THEN
        RETURN QUERY SELECT false, 'not_authorized'::text;
        RETURN;
    END IF;

    IF v_caller_role = 'guild_admin' AND p_guild <> COALESCE(v_caller_guild, '') THEN
        RETURN QUERY SELECT false, 'not_authorized'::text;
        RETURN;
    END IF;

    IF v_caller_role = 'server_admin' THEN
        SELECT server_number INTO v_target_server FROM public.guilds WHERE id = p_guild;
        IF v_caller_server IS NULL OR v_target_server IS NULL OR v_target_server <> v_caller_server THEN
            RETURN QUERY SELECT false, 'not_authorized'::text;
            RETURN;
        END IF;
    END IF;

    DELETE FROM public.shadowfront_squads
    WHERE guild = p_guild AND session_id = p_session_id AND LOWER(pseudo) = LOWER(p_pseudo);

    DELETE FROM public.event_participants
    WHERE guild = p_guild AND session_id = p_session_id AND LOWER(pseudo) = LOWER(p_pseudo)
      AND LOWER(event_name) LIKE '%shadowfront%';

    RETURN QUERY SELECT true, NULL::text;
END;
$function$;
